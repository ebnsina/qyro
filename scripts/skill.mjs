// Builds skills/qyro/SKILL.md from the docs in site/src/docs, so the skill never drifts from them.
// `node scripts/skill.mjs` writes it; `--check` fails when the committed file is stale.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const SITE = 'https://ebnsina.github.io/qyro';
const out = 'skills/qyro/SKILL.md';

function doc(slug) {
	const raw = readFileSync(`site/src/docs/${slug}.md`, 'utf8');
	const body = raw.replace(/^---\n[\s\S]*?\n---\n/, '').trim();
	return body;
}

/** The named `## ` sections of a page (all of them when none are named), headings pushed down a level. */
function sections(slug, names) {
	const body = doc(slug).replace(/^# .*\n+/, '');
	const parts = body.split(/^(?=## )/m);
	const intro = parts[0].startsWith('## ') ? '' : parts.shift();
	const picked = names ? parts.filter((p) => names.includes(p.slice(3, p.indexOf('\n')).trim())) : [intro, ...parts];
	if (names && picked.length != names.length) throw new Error(`docs/${slug}.md is missing a section: ${names.join(', ')}`);
	return picked
		.join('\n')
		.replace(/^(#{2,5}) /gm, '#$1 ')
		.replace(/\]\(\/docs\/([a-z-]+)\)/g, `](${SITE}/docs/$1.md)`)
		.trim();
}

const skill = `---
name: qyro
description: Add, configure and theme the Qyro video player (<qyro-player> web component, npm package "qyro") in any site or framework. Use when embedding video, HLS/DASH/live streams, captions or subtitles, storyboard thumbnails, theming a player, or turning on Seyr video analytics with Qyro.
---

# Qyro

<!-- Generated by scripts/skill.mjs from site/src/docs. Edit the docs, then run \`pnpm skill\`. -->

Qyro is one custom element, \`<qyro-player>\`, that plays HLS, DASH, live and MP4 with liquid glass controls. Use its attributes and methods; don't build custom controls around a bare \`<video>\`.

## Install and add a video

${sections('getting-started', ['Install', 'Add a video'])}

## Attributes

${sections('attributes')}

## JavaScript API

${sections('api')}

## Events

${sections('events')}

## Framework snippets

${sections('ai', ['Framework snippets'])}

## Analytics with Seyr

${sections('analytics', ['How the Seyr code is loaded'])}

## Common mistakes

${sections('ai', ['Common mistakes'])}

## Verify it works

${sections('ai', ['Verify it works'])}

## More

Full docs as Markdown: ${SITE}/llms-full.txt. Captions: ${SITE}/docs/captions.md. Thumbnails: ${SITE}/docs/thumbnails.md. Live: ${SITE}/docs/live.md. Theming tokens: ${SITE}/docs/theming.md.
`;

const lines = skill.split('\n').length;
if (lines > 320) throw new Error(`SKILL.md is ${lines} lines; keep it under about 300`);

if (process.argv.includes('--check')) {
	let current = '';
	try {
		current = readFileSync(out, 'utf8');
	} catch {}
	if (current != skill) {
		console.error(`${out} is missing or out of date with the docs. Run: pnpm skill`);
		process.exit(1);
	}
	console.log(`${out} is up to date (${lines} lines)`);
} else {
	mkdirSync('skills/qyro', { recursive: true });
	writeFileSync(out, skill);
	console.log(`Wrote ${out} (${lines} lines)`);
}
